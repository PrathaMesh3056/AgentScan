# agentscan/remediation/patch_generator.py
#
# Generates standard unified git diffs and GitHub Pull Request payloads
# from AgentScan FixPlan remediation actions.

from __future__ import annotations

import difflib
from pathlib import Path
from typing import Any

from agentscan.remediation.models import FixPlan
from agentscan.remediation.redaction import redact


def generate_unified_patch(plan: FixPlan, base_dir: Path | str | None = None) -> str:
    """
    Generate a standard unified git patch string from all actions in a FixPlan.

    The output format matches `git diff` / `git apply` conventions:
      --- a/<relative_path>
      +++ b/<relative_path>
      @@ -1,3 +1,3 @@
    """
    if not plan.actions:
        return ""

    base_path = Path(base_dir).resolve() if base_dir is not None else None
    patch_chunks: list[str] = []

    for action in plan.actions:
        if action.before == action.after:
            continue

        raw_path = Path(action.path)
        if base_path and raw_path.is_absolute():
            try:
                rel_path = raw_path.resolve().relative_to(base_path).as_posix()
            except ValueError:
                rel_path = raw_path.as_posix()
        else:
            rel_path = raw_path.as_posix().lstrip("/")

        from_lines = action.before.splitlines(keepends=True)
        to_lines = action.after.splitlines(keepends=True)

        diff = difflib.unified_diff(
            from_lines,
            to_lines,
            fromfile=f"a/{rel_path}",
            tofile=f"b/{rel_path}",
        )
        chunk = "".join(diff)
        if chunk:
            patch_chunks.append(chunk)

    return redact("\n".join(patch_chunks))


def generate_github_pr_payload(
    plan: FixPlan,
    branch_name: str = "agentscan/auto-heal",
    base_branch: str = "main",
    title: str = "[Security] Automated Remediation via AgentScan Self-Healing",
) -> dict[str, Any]:
    """
    Construct a structured payload for the GitHub REST API (POST /repos/{owner}/{repo}/pulls)
    and automated CI PR creation pipelines.
    """
    unified_diff = generate_unified_patch(plan)

    summary_rows: list[str] = [
        "| Finding ID | Action Kind | Target File |",
        "|---|---|---|",
    ]
    for action in plan.actions:
        summary_rows.append(
            f"| `{action.finding_id}` | `{action.kind}` | `{Path(action.path).name}` |"
        )

    body = f"""## AgentScan Self-Healing Automated Remediation

This automated Pull Request was generated by **AgentScan Self-Healing** in response to detected security vulnerabilities.

### Summary of Actions
- **Total Actions Planned**: {plan.total_actions}
- **Files Modified**: {len(plan.paths_affected)}

### Remediated Findings
{chr(10).join(summary_rows)}

### Instructions to Review
1. Inspect the attached unified diff or GitHub file changes.
2. Verify local tests with `pytest`.
3. Merge when validated.

*Generated autonomously by AgentScan Self-Healing.*
"""

    return redact(
        {
            "title": title,
            "head": branch_name,
            "base": base_branch,
            "body": body.strip(),
            "draft": False,
            "maintainer_can_modify": True,
            "metadata": {
                "total_actions": plan.total_actions,
                "paths_affected": plan.paths_affected,
                "patch": unified_diff,
                "sensitive": getattr(plan, "sensitive", True),
            },
        }
    )
